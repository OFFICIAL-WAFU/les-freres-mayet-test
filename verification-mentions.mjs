import fs from 'node:fs';import assert from 'node:assert/strict';import ts from 'typescript';
const code=ts.transpileModule(fs.readFileSync('src/lib/mentions.ts','utf8'),{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ESNext}}).outputText;
const {validerBibliotheque,insererMentions,fusionnerMentions,lireSauvegarde,preparerSauvegarde,dateHeureMention}=await import('data:text/javascript;base64,'+Buffer.from(code).toString('base64'));
const a={id:'11111111-1111-4111-8111-111111111111',titre:'Condition TEST',texte:'Texte TEST.\n\nDeuxième paragraphe.',usages:['devis'],archivee:false};
const b={id:'22222222-2222-4222-8222-222222222222',titre:'Autre TEST',texte:'Autre texte TEST.',usages:['facture','acompte'],archivee:false};
const bib={version:3,mentions:[a]};
assert.equal(insererMentions('Saisie existante',[a]),'Saisie existante\n\n'+a.texte);
assert.equal(insererMentions(insererMentions('Saisie existante',[a]),[a]),insererMentions('Saisie existante',[a]));
assert.equal(insererMentions('Saisie existante',[{...a,archivee:true}]),'Saisie existante');
const doc={conditions:insererMentions('',[a])};
const modifie={...a,texte:'Nouveau texte'};assert.equal(doc.conditions,a.texte);
assert.equal(fusionnerMentions(bib,[a,a].slice(0,1)).mentions.length,1);
assert.equal(fusionnerMentions(bib,[b]).mentions.length,2);
assert.throws(()=>fusionnerMentions(bib,[modifie]),/contenu différent/);
assert.throws(()=>fusionnerMentions(bib,[{...b,titre:' condition   TEST '}]),/contenu différent/);
assert.equal(bib.mentions[0].texte,a.texte);
assert.deepEqual(lireSauvegarde(JSON.parse(JSON.stringify(preparerSauvegarde(bib)))),[a]);
for(const mauvaise of [null,{}, {schema:2,format:'mayet-mentions',mentions:[a]}, {schema:1,format:'mayet-mentions',mentions:[a,a]}])assert.throws(()=>lireSauvegarde(mauvaise));
assert.throws(()=>validerBibliotheque({version:0,mentions:[{...a,titre:' '}]}));
assert.throws(()=>validerBibliotheque({version:0,mentions:[{...a,texte:'a'.repeat(2001)}]}));
assert.throws(()=>validerBibliotheque({version:0,mentions:[{...a,usages:['__proto__']}]}));
assert.throws(()=>insererMentions('a'.repeat(19990),[a]),/20 000/);
assert.equal(dateHeureMention('date',new Date('2026-10-07T23:30:00Z')),'08/10/2026');
assert.equal(dateHeureMention('heure',new Date('2026-10-07T23:30:00Z')),'01:30');
console.log('Mentions : copie indépendante, texte existant conservé, répétition sans doublon (multilignes), archives exclues, fusion sans remplacement, sauvegarde relue, données invalides refusées, date/heure de Paris.');
